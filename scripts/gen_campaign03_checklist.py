STATUS_ORDER = {"NOT_STARTED": 0, "IN_PROGRESS": 1, "BLOCKED": 2, "DONE": 3}


def default_status() -> dict:
    return {
        "updated": "",
        "workpackages": {
            f"{tid}.{wp[0]}": {"status": "NOT_STARTED", "notes": "", "verified": None}
            for tid, _t, _m, _d, wps in TASKS
            for wp in wps
        },
    }


def load_status() -> dict:
    if STATUS_FILE.exists():
        return json.loads(STATUS_FILE.read_text(encoding="utf-8"))
    status = default_status()
    STATUS_FILE.parent.mkdir(parents=True, exist_ok=True)
    STATUS_FILE.write_text(json.dumps(status, indent=2) + "\n", encoding="utf-8")
    return status


def save_status(status: dict) -> None:
    status["updated"] = __import__("datetime").datetime.now().isoformat(timespec="seconds")
    STATUS_FILE.write_text(json.dumps(status, indent=2) + "\n", encoding="utf-8")


def apply_set(status: dict, wp_id: str, new_status: str, note: str | None) -> None:
    if wp_id not in status["workpackages"]:
        raise SystemExit(f"unknown work package: {wp_id}")
    if new_status not in STATUS_ORDER:
        raise SystemExit(f"invalid status: {new_status}")
    entry = status["workpackages"][wp_id]
    entry["status"] = new_status
    if note is not None:
        entry["notes"] = note
    if new_status == "DONE":
        import datetime
        entry["verified"] = datetime.date.today().isoformat()


def render(status: dict) -> str:
    wps = status["workpackages"]
    total_wp = len(wps)
    done = sum(1 for e in wps.values() if e["status"] == "DONE")
    in_prog = sum(1 for e in wps.values() if e["status"] == "IN_PROGRESS")
    blocked = sum(1 for e in wps.values() if e["status"] == "BLOCKED")
    remaining = total_wp - done
    pct = round(100.0 * done / total_wp, 2) if total_wp else 0.0

    lines = [
        "# Campaign 03 — Architecture Intelligence Lab: Master Checklist",
        "",
        "**Generated by `python scripts/gen_campaign03_checklist.py` from"
        " `docs/campaign-03-status.json`. Do not edit statuses by hand.**",
        "",
        "## Status summary (computed, never hand-written)",
        "",
        f"- Total major tasks: **45**",
        f"- Total work packages: **{total_wp}**",
        f"- Completed work packages: **{done}**",
        f"- In-progress work packages: **{in_prog}**",
        f"- Blocked work packages: **{blocked}**",
        f"- Remaining work packages: **{remaining}**",
        f"- Verified completion: **{pct}%** ({done}/{total_wp})",
        "",
        "Statuses: `NOT_STARTED` `IN_PROGRESS` `BLOCKED` `DONE`.",
        "A work package is DONE only after its behavior has been verified and the",
        "verification recorded below (evidence column / notes).",
        "",
    ]
    by_milestone: dict[int, list] = {}
    for tid, title, ms, deps, wplist in TASKS:
        by_milestone.setdefault(ms, []).append((tid, title, deps, wplist))
    for ms in sorted(by_milestone):
        lines.append(f"## Milestone {ms}")
        lines.append("")
        for tid, title, deps, wplist in by_milestone[ms]:
            dep_txt = ", ".join(deps) if deps else "—"
            task_done = all(wps[f"{tid}.{w[0]}"]["status"] == "DONE" for w in wplist)
            lines.append(f"### Task {tid} — {title} " + ("✅" if task_done else ""))
            lines.append("")
            lines.append(f"*Depends on:* {dep_txt}")
            lines.append("")
            lines.append("| WP | Work package | Acceptance criteria | Evidence expected | Status | Verified | Notes |")
            lines.append("|----|--------------|---------------------|--------------------|--------|----------|-------|")
            for w in wplist:
                wpid = f"{tid}.{w[0]}"
                e = wps[wpid]
                lines.append(
                    f"| `{wpid}` | {w[1]} — {w[2]} (deps: {w[3]}) | {w[4]} | {w[5]} | "
                    f"`{e['status']}` | {e['verified'] or '—'} | {e['notes'] or '—'} |"
                )
            lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"*Last generated: {status.get('updated') or 'now'} — {done}/{total_wp} work packages verified.*")
    return "\n".join(lines) + "\n"


def main() -> None:
    args = sys.argv[1:]
    status = load_status()
    i = 0
    while i < len(args):
        if args[i] == "--set":
            apply_set(status, args[i + 1], args[i + 2], None)
            i += 3
        elif args[i] == "--note":
            wpid = args[i + 1]
            status["workpackages"][wpid]["notes"] = args[i + 2]
            i += 3
        else:
            i += 1
    save_status(status)
    CHECKLIST_FILE.write_text(render(status), encoding="utf-8")
    wps = status["workpackages"]
    done = sum(1 for e in wps.values() if e["status"] == "DONE")
    print(f"checklist written: {CHECKLIST_FILE}")
    print(f"work packages: {len(wps)}, done: {done}")


if __name__ == "__main__":
    main()
