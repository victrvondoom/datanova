"""Generates FEATURE_SEMANTICS.md + feature_semantics.json from the champion
artifact schema (catalog: feat_semantic_names_registry).

Validates that every feature in the served artifact has a registered
definition; exits non-zero if any feature is unexplained. Regenerate after
any feature-schema change: python scripts/generate_feature_semantics.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from packages.features.semantics import validate_coverage

MANIFEST_PATH = "experiments/champion_bundle.pkl.manifest.json"
OUT_MD = "FEATURE_SEMANTICS.md"
OUT_JSON = "feature_semantics.json"


def build(feature_names, model_id, run_id):
    entries = validate_coverage(feature_names)  # raises KeyError when unexplained
    lines = [
        "# Feature Semantic Registry",
        "",
        f"Semantic definitions for every feature in the served champion "
        f"artifact (`{model_id}`, run `{run_id}`). Generated by "
        f"`scripts/generate_feature_semantics.py`; validated against "
        f"`packages/features/temporal.py` and `packages/features/pipeline.py`.",
        "",
        f"**Features covered: {len(entries)}** (structural + dynamic one-hot "
        "indicators from the training-partition vocabulary).",
        "",
        "| Feature | Family | Unit | Definition | Derived from |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        derived = "; ".join(e.derived_from)
        definition = e.definition.replace("|", "\\|")
        lines.append(f"| `{e.name}` | {e.family} | {e.unit} | {definition} | {derived} |")
    lines += [
        "",
        "## Rules",
        "",
        "- Unknown features fail generation (the registry may never silently "
        "drift from the artifact schema).",
        "- Categorical one-hot indicators (`ch_*`, `cat_*`) are documented by "
        "rule; their vocabulary comes from the training partition only.",
        "- All rolling features are strictly causal (prior events only).",
        "",
    ]
    return "\n".join(lines), [
        {
            "name": e.name,
            "definition": e.definition,
            "unit": e.unit,
            "family": e.family,
            "derived_from": e.derived_from,
        }
        for e in entries
    ]


def main() -> int:
    with open(MANIFEST_PATH, encoding="utf-8") as f:
        manifest = json.load(f)
    feature_names = manifest.get("feature_names")
    if not feature_names:
        print(f"ERROR: {MANIFEST_PATH} has no feature_names; refusing to "
              "generate an empty registry.")
        return 1
    try:
        md, registry = build(feature_names, manifest.get("model_id", "?"),
                              manifest.get("run_id", "?"))
    except KeyError as exc:
        print(f"ERROR: {exc}")
        return 1
    with open(OUT_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(md)
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        json.dump(
            {
                "run_id": manifest.get("run_id"),
                "model_id": manifest.get("model_id"),
                "feature_count": len(registry),
                "features": registry,
            },
            f,
            indent=2,
        )
        f.write("\n")
    print(f"Written {OUT_MD} and {OUT_JSON} ({len(registry)} features, all explained).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
