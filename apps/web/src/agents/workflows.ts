/**
 * Workflow registry — the 11 named financial workflows. Each definition is a
 * persisted, versioned DAG: agent nodes, data sources, conditional branches,
 * human-approval checkpoints and final outputs. The canvas renders exactly
 * these definitions; there is no second graph.
 */

import type { WfEdge, WfNode, WorkflowDef, ParallelGroup, ConditionSpec, NodeKind } from "./types";

const node = (id: string, kind: NodeKind, label: string, extra: Partial<WfNode> = {}): WfNode => ({
  id, kind, label, ...extra,
});
const ag = (id: string, agentId: string, label: string, extra: Partial<WfNode> = {}): WfNode =>
  node(id, "agent", label, { agentId, ...extra });
const edge = (from: string, to: string, kind: WfEdge["kind"] = "handoff", label?: string, condition?: ConditionSpec): WfEdge => ({
  id: `e-${from}->${to}`, from, to, kind, label, condition,
});
const group = (id: string, label: string, nodeIds: string[]): ParallelGroup => ({ id, label, nodeIds });

const wf = (
  id: string, name: string, description: string, objective: string,
  nodes: WfNode[], edges: WfEdge[], parallelGroups: ParallelGroup[],
  meta: Partial<Pick<WorkflowDef, "requiredInputs" | "toolDependencies" | "expectedArtifacts" | "completionConditions" | "evaluationBenchmark" | "defaultMode">>,
): WorkflowDef => ({
  id, name, version: 1, description, objective,
  requiredInputs: ["caseId"], toolDependencies: [],
  nodes, edges, parallelGroups,
  expectedArtifacts: ["final-outcome"],
  completionConditions: ["All agent tasks reached a terminal state", "Human approval checkpoint resolved"],
  evaluationBenchmark: "Deterministic synthetic-scenario benchmark (see docs/WORKFLOW_BENCHMARK_RESULTS.md)",
  defaultMode: "simulation",
  ...meta,
});

const humanApproval = (id: string, prompt: string): WfNode =>
  node(id, "approval", "Human approval", { approvalPrompt: prompt, sensitive: true });
const outputNode = (id: string, label: string, external: boolean): WfNode =>
  node(id, "output", label, { external, idempotencyKey: id });
